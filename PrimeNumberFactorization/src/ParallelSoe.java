import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

public class ParallelSoe {
    private final int n;
    private final int k;
    private final int runs;
    private int[] primes;
    private double timeUsagesSoePara;
    private double timeUsagesFactorizationPara;
    private final Map<Long, List<Long>> factorResults;

    public ParallelSoe(int n, int k, int runs) {
        this.n = n;
        this.k = k;
        this.runs = runs;
        factorResults = new TreeMap<>();
    }

    /**
     * Runs the parallel sieve and the parallel factorization several times, and stores the median time usage.
     */
    public void run() {
        List<Double> timeListSoePara = new ArrayList<>();
        List<Double> timeListFactorPara = new ArrayList<>();

        for (int i = 0; i < runs; i++) {
            ParallelSieve soePara = new ParallelSieve(n, k);

            long startTimeSoePara = System.nanoTime();
            int[] primeArray = soePara.getPrimes();
            long endTimeSoePara = System.nanoTime();

            long startTimeFactorization = System.nanoTime();
            Map<Long, List<Long>> factors = factorizeLargestNumbersInParallel(primeArray);
            long endTimeFactorization = System.nanoTime();

            timeListSoePara.add(toMilliseconds(startTimeSoePara, endTimeSoePara));
            timeListFactorPara.add(toMilliseconds(startTimeFactorization, endTimeFactorization));

            // Tar vare på resultatene fra siste kjøring, slik at de kan sammenlignes og skrives til fil.
            primes = primeArray;
            factorResults.clear();
            factorResults.putAll(factors);
        }

        timeUsagesSoePara = median(timeListSoePara);
        timeUsagesFactorizationPara = median(timeListFactorPara);
    }

    /**
     * Factorizes the 100 largest numbers below n*n in parallel.
     *
     * @param primeArray primes generated by the sieve.
     * @return map with the number as key and the factors as value.
     */
    private Map<Long, List<Long>> factorizeLargestNumbersInParallel(int[] primeArray) {
        Map<Long, List<Long>> factors = new TreeMap<>();
        long maxNumber = ((long) n * n) - 1;

        // Gjenbruker samme thread pool for alle de 100 faktoriseringene.
        PrimeFactorization.ParallelFactorizer factorizer = new PrimeFactorization.ParallelFactorizer(k, primeArray);

        for (long number = maxNumber - 99; number <= maxNumber; number++) {
            factors.put(number, factorizer.factorize(number));
        }

        factorizer.shutdown();
        return factors;
    }

    /**
     * Writes the factors to file using the provided Oblig3Precode class.
     */
    public void writeFactors() {
        Oblig3Precode preCode = new Oblig3Precode(n);

        for (Map.Entry<Long, List<Long>> entry : factorResults.entrySet()) {
            for (long factor : entry.getValue()) {
                preCode.addFactor(entry.getKey(), factor);
            }
        }

        preCode.writeFactors("parallel");
    }

    private double median(List<Double> values) {
        values.sort(Double::compareTo);
        return values.get(values.size() / 2);
    }

    private double toMilliseconds(long startTime, long endTime) {
        return (endTime - startTime) / 1_000_000.0;
    }

    public int[] getPrimes() {
        return primes;
    }

    public double getMedianSieveTime() {
        return timeUsagesSoePara;
    }

    public double getMedianFactorizationTime() {
        return timeUsagesFactorizationPara;
    }

    public Map<Long, List<Long>> getFactorResults() {
        return factorResults;
    }
}