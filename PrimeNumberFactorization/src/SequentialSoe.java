import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

public class SequentialSoe {
    private final int n;
    private final int runs;
    private int[] primes;
    private double medianTimeSoe;
    private double medianTimeFactorization;
    private final Map<Long, List<Long>> factorResults;

    public SequentialSoe(int n, int runs) {
        this.n = n;
        this.runs = runs;
        factorResults = new TreeMap<>();
    }

    /**
     * Runs the sequential sieve and the sequential factorization several times, and stores the median time usage.
     */
    public void run() {
        List<Double> timeListSoe = new ArrayList<>();
        List<Double> timeListFactorization = new ArrayList<>();

        for (int i = 0; i < runs; i++) {
            SieveOfEratosthenes soe = new SieveOfEratosthenes(n);

            long startTimeSoe = System.nanoTime();
            int[] primeNumbers = soe.getPrimes();
            long endTimeSoe = System.nanoTime();

            long startTimeFactorization = System.nanoTime();
            Map<Long, List<Long>> factors = factorizeLargestNumbersSequentially(primeNumbers);
            long endTimeFactorization = System.nanoTime();

            timeListSoe.add(toMilliseconds(startTimeSoe, endTimeSoe));
            timeListFactorization.add(toMilliseconds(startTimeFactorization, endTimeFactorization));

            // FORBEDRET: tar vare på resultatene fra siste kjøring, slik at de kan sammenlignes og skrives til fil.
            primes = primeNumbers;
            factorResults.clear();
            factorResults.putAll(factors);
        }

        medianTimeSoe = median(timeListSoe);
        medianTimeFactorization = median(timeListFactorization);
    }

    /**
     * Factorizes the 100 largest numbers below n*n sequentially.
     *
     * @param primeNumbers primes generated by the sieve.
     * @return map with the number as key and the factors as value.
     */
    private Map<Long, List<Long>> factorizeLargestNumbersSequentially(int[] primeNumbers) {
        Map<Long, List<Long>> factors = new TreeMap<>();
        long maxNumber = ((long) n * n) - 1;

        for (long number = maxNumber - 99; number <= maxNumber; number++) {
            factors.put(number, PrimeFactorization.primeCalculation(number, primeNumbers));
        }

        return factors;
    }

    /**
     * Writes the factors to file using the provided Oblig3Precode class.
     */
    public void writeFactors() {
        Oblig3Precode preCode = new Oblig3Precode(n);

        for (Map.Entry<Long, List<Long>> entry : factorResults.entrySet()) {
            for (long factor : entry.getValue()) {
                preCode.addFactor(entry.getKey(), factor);
            }
        }

        preCode.writeFactors("sequential");
    }

    private double median(List<Double> values) {
        values.sort(Double::compareTo);
        return values.get(values.size() / 2);
    }

    private double toMilliseconds(long startTime, long endTime) {
        return (endTime - startTime) / 1_000_000.0;
    }

    public int[] getPrimes() {
        return primes;
    }

    public double getMedianSieveTime() {
        return medianTimeSoe;
    }

    public double getMedianFactorizationTime() {
        return medianTimeFactorization;
    }

    public Map<Long, List<Long>> getFactorResults() {
        return factorResults;
    }
}